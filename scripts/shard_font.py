#!/usr/bin/env python3
"""Build the full TsangerJinKai05 W04 webfont from the original TTF."""

import argparse
from hashlib import sha256
from io import BytesIO
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

from subset_font import collect_chars

ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / "assets" / "fonts"
LEGACY_FONT = FONT_DIR / "tsanger-jinkai05-w04.woff2"
FAMILY = "JinKai Local"
# Keep the old family name available to cached styles and existing callers.
FAMILY_ALIASES = (FAMILY, "JinKai N1")
SHARD_SIZE = 384


def unicode_points(font):
    return {
        point
        for table in font["cmap"].tables
        if table.isUnicode() and table.format != 14
        for point in table.cmap
    }


def variation_sequences(font):
    return {
        (base, selector)
        for table in font["cmap"].tables
        if table.format == 14
        for selector, entries in table.uvsDict.items()
        for base, _ in entries
    }


def unicode_ranges(points):
    ranges = []
    ordered = iter(sorted(points))
    start = end = next(ordered)
    for point in ordered:
        if point != end + 1:
            ranges.append((start, end))
            start = point
        end = point
    ranges.append((start, end))
    return ", ".join(
        f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}"
        for start, end in ranges
    )


def make_groups(points, legacy_points):
    # Keep familiar page text together, so rendering current copy makes few requests.
    site_text, _ = collect_chars()
    shared = points & (legacy_points | set(map(ord, site_text)))
    groups = [
        ("latin", {point for point in points if point <= 0xFF}),
        ("site", {point for point in shared if point > 0xFF}),
    ]
    remaining = sorted(points.difference(*(group for _, group in groups)))
    groups.extend(
        (f"extra-{index // SHARD_SIZE + 1:03}", set(remaining[index:index + SHARD_SIZE]))
        for index in range(0, len(remaining), SHARD_SIZE)
    )
    return [(name, group) for name, group in groups if group]


def build_shard(source, options, points, sequences):
    with TTFont(BytesIO(source), recalcTimestamp=False) as font:
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=points)
        subsetter.subset(font)
        if 0x3000 in points:
            # Preserve the existing two-character indentation in the letters.
            space = font.getBestCmap()[0x3000]
            _, bearing = font["hmtx"][space]
            font["hmtx"][space] = (font["head"].unitsPerEm, bearing)
        font.flavor = "woff2"
        output = BytesIO()
        font.save(output)
    data = output.getvalue()
    with TTFont(BytesIO(data)) as shard:
        if unicode_points(shard) != points:
            raise ValueError("Shard cmap does not match its unicode-range")
        if variation_sequences(shard) != sequences:
            raise ValueError("Shard cmap lost a Unicode variation sequence")
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="Original TsangerJinKai05-W04 TTF")
    args = parser.parse_args()

    source = args.source.read_bytes()
    with TTFont(BytesIO(source), checkChecksums=2) as original, TTFont(LEGACY_FONT) as legacy:
        if original["name"].getDebugName(6) != legacy["name"].getDebugName(6):
            parser.error("The source must match the site's TsangerJinKai05 W04 font")
        points = unicode_points(original)
        sequences = variation_sequences(original)
        if any(base not in points for base, _ in sequences):
            parser.error("The source has variation sequences without a base character")
        legacy_points = unicode_points(legacy)
        if not legacy_points <= points or points == legacy_points:
            parser.error("The source must cover the current subset and the rest of the font")

    options = subset.Options()
    options.layout_features = ["*"]
    options.retain_all_variation_sequences = True
    options.name_IDs += [8, 13, 14]
    groups = make_groups(points, legacy_points)
    shard_dir = FONT_DIR / "jinkai"
    shard_dir.mkdir(exist_ok=True)
    css = [
        "/* Generated by scripts/shard_font.py from TsangerJinKai05 W04. */",
        f':root {{ --site-font: "{FAMILY}"; }}',
    ]
    total = 0
    for name, group in groups:
        group_sequences = {(base, selector) for base, selector in sequences if base in group}
        data = build_shard(source, options, group, group_sequences)
        filename = f"{name}-{sha256(data).hexdigest()[:12]}.woff2"
        (shard_dir / filename).write_bytes(data)
        total += len(data)
        ranges = unicode_ranges(group)
        for family in FAMILY_ALIASES:
            css.append(
                f'@font-face {{\n'
                f'  font-family: "{family}";\n'
                f'  font-style: normal;\n'
                f'  font-weight: 400;\n'
                f'  font-display: swap;\n'
                f'  src: url("./jinkai/{filename}") format("woff2");\n'
                f'  unicode-range: {ranges};\n'
                f'}}'
            )
    (FONT_DIR / "jinkai.css").write_bytes(("\n".join(css) + "\n").encode("utf-8"))
    print(f"{len(points):,} Unicode code points in {len(groups)} WOFF2 files ({total:,} bytes)")


if __name__ == "__main__":
    main()
